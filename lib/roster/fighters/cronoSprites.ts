function decodeCronoFrame(rows: readonly string[]): IndexedFrame {
  return rows.map((row) => {
    const out: number[] = [];
    for (let i = 0; i < row.length; i++) {
      out.push(CHAR_TO_INDEX[row[i]] ?? 0);
    }
    return out;
  });
}

