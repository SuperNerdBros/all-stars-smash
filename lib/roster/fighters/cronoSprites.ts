function buildCronoDualEra(): { snesChart: PixelChart; nesChart: PixelChart } {
  const ready0 = decodeCronoFrame(CRONO_READY_0);
  const draw1 = decodeCronoFrame(CRONO_DRAW_1);
  const overhead2 = decodeCronoFrame(CRONO_OVERHEAD_2);
  const thrust3 = decodeCronoFrame(CRONO_THRUST_3);
  const dash1 = decodeCronoFrame(CRONO_DASH_1);
  const dash2 = decodeCronoFrame(CRONO_DASH_2);
  const sweep1 = decodeCronoFrame(CRONO_SWEEP_1);
  const sweep2 = decodeCronoFrame(CRONO_SWEEP_2);
  const cast1 = decodeCronoFrame(CRONO_CAST_1);
  const jump1 = decodeCronoFrame(CRONO_JUMP_1);
  const hurt1 = decodeCronoFrame(CRONO_HURT_1);
  const hurt2 = decodeCronoFrame(CRONO_HURT_2);

  const snesChart: PixelChart = {
    idle: { frames: [ready0, draw1], ticksPerFrame: CRONO_TICKS.idle },
    walk: { frames: [dash1, dash2], ticksPerFrame: CRONO_TICKS.walk },
    jump: { frames: [jump1, overhead2], ticksPerFrame: CRONO_TICKS.jump },
    attack: { frames: [draw1, overhead2, thrust3], ticksPerFrame: CRONO_TICKS.attack },
    smash: { frames: [overhead2, sweep1, sweep2], ticksPerFrame: CRONO_TICKS.smash },
    special: { frames: [cast1, jump1], ticksPerFrame: CRONO_TICKS.special },
    hurt: { frames: [hurt1, hurt2], ticksPerFrame: CRONO_TICKS.hurt },
  };

  return {
    snesChart,
    nesChart: buildNesDemakeChart(snesChart),
  };
}

export const CRONO_DUAL_ERA = buildCronoDualEra();
