function buildJeffDualEra(): { snesChart: PixelChart; nesChart: PixelChart } {
  const diag1 = decodeEarthboundFrame(JEFF_DIAG_1);
  const front1 = decodeEarthboundFrame(JEFF_FRONT_1);
  const side1 = decodeEarthboundFrame(JEFF_SIDE_1);
  const side2 = decodeEarthboundFrame(JEFF_SIDE_2);
  const diag2 = decodeEarthboundFrame(JEFF_DIAG_2);
  const cheer = decodeEarthboundFrame(JEFF_CHEER);
  const hurt = decodeEarthboundFrame(JEFF_HURT);

  return buildEarthboundDualEra({
    idle: [diag1, shiftEarthboundFrame(diag1, 0, 1)],
    walk: [side1, side2],
    jump: [cheer, side2],
    attack: [overlayEarthboundFx(shiftEarthboundFrame(side2, -1), JEFF_LASER_FX), overlayEarthboundFx(shiftEarthboundFrame(diag2, -1), JEFF_LASER_FX)],
    smash: [shiftEarthboundFrame(diag1, -1), overlayEarthboundFx(shiftEarthboundFrame(side2, -1), JEFF_ROCKET_FX)],
    special: [overlayEarthboundFx(cheer, JEFF_ROCKET_FX), overlayEarthboundFx(front1, JEFF_ROCKET_FX)],
    hurt: [hurt],
  });
}

function buildPooDualEra(): { snesChart: PixelChart; nesChart: PixelChart } {
  const diag1 = decodeEarthboundFrame(POO_DIAG_1);
  const front1 = decodeEarthboundFrame(POO_FRONT_1);
  const side1 = decodeEarthboundFrame(POO_SIDE_1);
  const side2 = decodeEarthboundFrame(POO_SIDE_2);
  const diag2 = decodeEarthboundFrame(POO_DIAG_2);
  const cheer = decodeEarthboundFrame(POO_CHEER);
  const hurt = decodeEarthboundFrame(POO_HURT);

  return buildEarthboundDualEra({
    idle: [diag1, shiftEarthboundFrame(diag1, 0, 1)],
    walk: [side1, side2],
    jump: [cheer, side2],
    attack: [overlayEarthboundFx(shiftEarthboundFrame(side2, -1), POO_SWORD_FX), overlayEarthboundFx(shiftEarthboundFrame(diag2, -1), POO_SWORD_FX)],
    smash: [shiftEarthboundFrame(diag1, -1), overlayEarthboundFx(shiftEarthboundFrame(side2, -1), POO_SWORD_FX)],
    special: [overlayEarthboundFx(cheer, POO_STAR_FX), overlayEarthboundFx(front1, POO_STAR_FX)],
    hurt: [hurt],
  });
}

