function buildNessDualEra(): { snesChart: PixelChart; nesChart: PixelChart } {
  const diag1 = decodeEarthboundFrame(NESS_DIAG_1);
  const front1 = decodeEarthboundFrame(NESS_FRONT_1);
  const side1 = decodeEarthboundFrame(NESS_SIDE_1);
  const side2 = decodeEarthboundFrame(NESS_SIDE_2);
  const diag2 = decodeEarthboundFrame(NESS_DIAG_2);
  const cheer = decodeEarthboundFrame(NESS_CHEER);
  const hurt = decodeEarthboundFrame(NESS_HURT);

  return buildEarthboundDualEra({
    idle: [diag1, shiftEarthboundFrame(diag1, 0, 1)],
    walk: [side1, side2],
    jump: [cheer, side2],
    attack: [overlayEarthboundFx(shiftEarthboundFrame(side2, -1), NESS_YOYO_FX), overlayEarthboundFx(shiftEarthboundFrame(diag2, -1), NESS_YOYO_FX)],
    smash: [shiftEarthboundFrame(diag1, -1), overlayEarthboundFx(shiftEarthboundFrame(side2, -1), NESS_BAT_FX)],
    special: [overlayEarthboundFx(cheer, NESS_PK_FX), overlayEarthboundFx(front1, NESS_PK_FX)],
    hurt: [hurt],
  });
}

function buildPaulaDualEra(): { snesChart: PixelChart; nesChart: PixelChart } {
  const diag1 = decodeEarthboundFrame(PAULA_DIAG_1);
  const front1 = decodeEarthboundFrame(PAULA_FRONT_1);
  const side1 = decodeEarthboundFrame(PAULA_SIDE_1);
  const side2 = decodeEarthboundFrame(PAULA_SIDE_2);
  const diag2 = decodeEarthboundFrame(PAULA_DIAG_2);
  const cheer = decodeEarthboundFrame(PAULA_CHEER);
  const hurt = decodeEarthboundFrame(PAULA_HURT);

  return buildEarthboundDualEra({
    idle: [diag1, shiftEarthboundFrame(diag1, 0, 1)],
    walk: [side1, side2],
    jump: [cheer, side2],
    attack: [overlayEarthboundFx(shiftEarthboundFrame(side2, -1), PAULA_PAN_FX), overlayEarthboundFx(shiftEarthboundFrame(diag2, -1), PAULA_PAN_FX)],
    smash: [shiftEarthboundFrame(diag1, -1), overlayEarthboundFx(shiftEarthboundFrame(cheer, -1), PAULA_PSI_FX)],
    special: [overlayEarthboundFx(cheer, PAULA_PSI_FX), overlayEarthboundFx(front1, PAULA_PSI_FX)],
    hurt: [hurt],
  });
}

